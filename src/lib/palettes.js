export const DEFAULT_PALETTE_GROUP = "partly";

export function resolvePalette(group, isDay = true, mode = "light") {
  const palette = PALETTES[group] || PALETTES[DEFAULT_PALETTE_GROUP];
  const base = palette[mode === "dark" ? "dark" : "light"];
  return {
    ...base,
    group: PALETTES[group] ? group : DEFAULT_PALETTE_GROUP,
    hero: isDay ? base.hero : NIGHT_HERO[group] || NIGHT_HERO.partly,
  };
}

export function paletteCssVariables(palette) {
  return {
    "--primary": palette.primary,
    "--primary-foreground": palette.onPrimary,
    "--primary-container": palette.primaryContainer,
    "--on-primary-container": palette.onPrimaryContainer,
    "--secondary": palette.secondary,
    "--secondary-foreground": palette.onPrimary,
    "--secondary-container": palette.secondaryContainer,
    "--on-secondary-container": palette.onSecondaryContainer,
    "--tertiary": palette.tertiary,
    "--tertiary-container": palette.tertiaryContainer,
    "--on-tertiary-container": palette.onTertiaryContainer,
    "--ring": palette.primary,
    "--hero-bg": palette.hero.bg,
    "--hero-ink": palette.hero.ink,
    "--hero-muted": palette.hero.muted,
    "--hero-line": palette.hero.line,
    "--hero-art-primary": palette.hero.primary,
    "--hero-art-cloud": palette.hero.cloud,
    "--hero-art-detail": palette.hero.detail,
    "--hero-glow": palette.hero.glow,
  };
}
